      <ul>
        <li>
          To what extent does post-event information distort eyewitness memory of a
          witnessed event?
          <em> Why it works:</em> it sits on a large experimental literature, and it
          invites evaluation of how far laboratory findings generalise to real
          witnesses.
        </li>
        <li>
          To what extent is heavy social-media use associated with depressive
          symptoms in adolescents, and does the evidence support a causal link?
          <em> Why it works:</em> it builds the correlation-versus-causation
          distinction into the question, and the literature contains genuinely
          conflicting findings to weigh.
        </li>
        <li>
          To what extent do conformity effects observed in laboratory experiments
          generalise across cultures?
          <em> Why it works:</em> it sets classic findings against later
          cross-cultural work, so critical comparison is not an add-on but the
          essay itself.
        </li>
      </ul>

